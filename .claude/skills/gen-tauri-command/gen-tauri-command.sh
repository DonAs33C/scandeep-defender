#!/usr/bin/env bash
# Generate Tauri Command - Script for gen-tauri-command skill
# Usage: ./gen-tauri-command.sh <command_name> <payload_fields> [return_type]

set -euo pipefail

PROJECT_ROOT="D:/ClaudeCode/Projects/ScanDeep Defender"
SRC_TAURI="$PROJECT_ROOT/src-tauri"

# Parse arguments
COMMAND_NAME="${1:-}"
PAYLOAD_FIELDS="${2:-}"
RETURN_TYPE="${3:-()}"

if [[ -z "$COMMAND_NAME" || -z "$PAYLOAD_FIELDS" ]]; then
    echo "Usage: $0 <command_name> <payload_fields> [return_type]"
    echo "Example: $0 get_scan_status 'scan_id: String' 'ScanStatus'"
    echo "Example: $0 list_scans 'limit: usize, offset: usize' 'Vec<ScanRecord>'"
    exit 1
fi

# Convert command_name to PascalCase for TypeScript
PASCAL_NAME=$(echo "$COMMAND_NAME" | sed -r 's/(^|_)([a-z])/\U\2/g')

# Determine command domain from existing structure
# scan, settings, history, quarantine
DOMAIN="scan"
case "$COMMAND_NAME" in
    *scan*|*check_duplicate|*poll_result) DOMAIN="scan" ;;
    *api_key*|*auto_scan|*config|*watcher_key*|*browser) DOMAIN="settings" ;;
    *history*|*clear_history) DOMAIN="history" ;;
    *quarantine*|*restore*|*delete_permanently) DOMAIN="quarantine" ;;
    *job*|*queue*) DOMAIN="job" ;;
esac

# Parse payload fields to TypeScript
# Input: "scan_id: String, limit: usize" -> Output: "scanId: string; limit: number;"
TS_PARAMS=$(echo "$PAYLOAD_FIELDS" | sed -E 's/([a-zA-Z_][a-zA-Z0-9_]*): ([A-Za-z<>\[\], ]+)/\1: \2/g' | \
    sed -E 's/([a-z])([A-Z])/\1_\2/g' | tr '[:upper:]' '[:lower:]' | \
    sed -E 's/([a-z])_([a-z])/\1\U\2/g' | \
    sed -E 's/(\w+): (String|&str)/\1: string/g' | \
    sed -E 's/(\w+): (usize|u32|u64|i32|i64)/\1: number/g' | \
    sed -E 's/(\w+): (bool)/\1: boolean/g' | \
    sed -E 's/(\w+): (Vec<(.+)>)/\1: \2/g' | \
    sed -E 's/(\w+): (Option<(.+)>)/\1: \2 | null/g' | \
    sed 's/, /; /g')

# If TS_PARAMS is empty after processing, use basic conversion
if [[ -z "$TS_PARAMS" || "$TS_PARAMS" == "$PAYLOAD_FIELDS" ]]; then
    TS_PARAMS=$(echo "$PAYLOAD_FIELDS" | \
        sed -E 's/(\w+): (String|&str)/\1: string/g' | \
        sed -E 's/(\w+): (usize|u32|u64|i32|i64)/\1: number/g' | \
        sed -E 's/(\w+): (bool)/\1: boolean/g' | \
        sed 's/, /; /g')
fi

echo "Generating Tauri command: $COMMAND_NAME"
echo "Domain: $DOMAIN"
echo "Payload: $PAYLOAD_FIELDS"
echo "Return: $RETURN_TYPE"
echo "TS Params: $TS_PARAMS"
echo "Pascal Name: $PASCAL_NAME"

# 1. Create Rust command file
RUST_FILE="$SRC_TAURI/src/commands/$DOMAIN/${COMMAND_NAME}.rs"
mkdir -p "$(dirname "$RUST_FILE")"

cat > "$RUST_FILE" << EOF
// $COMMAND_NAME - Tauri Command
// Auto-generated by gen-tauri-command skill

use std::sync::Arc;
use tauri::State;
use crate::app_state::AppState;

/// TODO: Add description
#[tauri::command]
pub async fn ${COMMAND_NAME}(
    ${PAYLOAD_FIELDS}
    state: State<'_, Arc<AppState>>,
) -> Result<${RETURN_TYPE}, String> {
    // TODO: Implement ${COMMAND_NAME}
    // Access state: state.db, state.pipeline, state.queue, state.keys, state.config, state.auto_scan
    unimplemented!("${COMMAND_NAME} not yet implemented")
}
EOF

echo "Created: $RUST_FILE"

# 2. Update TypeScript types
TS_FILE="$PROJECT_ROOT/src/types/index.ts"

# Find the Tauri Command Payload Types section and add before it
# We'll append to the file for now
cat >> "$TS_FILE" << EOF

// ============================================================================
// ${PASCAL_NAME} Command Types (Auto-generated)
// ============================================================================

/** Payload for ${COMMAND_NAME} command */
export interface ${PASCAL_NAME}Payload {
  ${TS_PARAMS}
}

/** Return type for ${COMMAND_NAME} command */
export interface ${PASCAL_NAME}Return {
  // TODO: Define return type matching Rust ${RETURN_TYPE}
}
EOF

echo "Updated: $TS_FILE"

# 3. Show next steps
echo ""
echo "=== Next Steps ==="
echo "1. Implement the command logic in: $RUST_FILE"
echo "2. Add the command to tauri::generate_handler![] in main.rs:"
echo "   commands::${DOMAIN}::${COMMAND_NAME},"
echo "3. Import in main.rs if needed:"
echo "   mod commands;"
echo "   // then in generate_handler![] add the command"
echo "4. Use in frontend:"
echo "   import { invoke } from \"@tauri-apps/api/core\";"
echo "   import type { ${PASCAL_NAME}Payload, ${PASCAL_NAME}Return } from \"../types\";"
echo "   const result = await invoke<${PASCAL_NAME}Return>(\"${COMMAND_NAME}\", { ... } as ${PASCAL_NAME}Payload);"